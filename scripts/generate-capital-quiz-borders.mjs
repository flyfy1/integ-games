// Dev-time generator for src/games/capital-quiz/borders.ts. Not used at runtime.
// Usage: node scripts/generate-capital-quiz-borders.mjs <countries-50m.json> <countryInfo.txt> <out.ts>
// Inputs, both downloaded separately:
//   - world-atlas@2 countries-50m TopoJSON (Natural Earth, public domain): two countries share a land border when
//     their polygons share a TopoJSON arc.
//   - GeoNames countryInfo.txt (CC BY 4.0): the "neighbours" column, an independently curated list.
// A pair is written as a neighbour only when BOTH sources agree. Pairs only one source knows (overseas territories,
// disputed areas, tiny borders lost to the 50m simplification) go to the "unsure" list: never asked as an answer and
// never offered as a wrong option either, so no question can have two right answers.
import { readFileSync, writeFileSync } from 'node:fs';

const [topoPath, infoPath, out] = process.argv.slice(2);
const topo = JSON.parse(readFileSync(topoPath, 'utf8'));
const info = readFileSync(infoPath, 'utf8').split('\n').filter((l) => l && !l.startsWith('#')).map((l) => l.split('\t'));

const numToIso = new Map(info.map((r) => [r[2], r[0]]));
const geonames = new Map(info.map((r) => [r[0], new Set((r[17] || '').split(',').filter(Boolean))]));
// Natural Earth splits off a few areas the bank treats as part of a member state.
const BY_NAME = { Somaliland: 'SO', 'N. Cyprus': 'CY', Kosovo: 'XK' };

const bank = new Set([...readFileSync(new URL('../src/games/capital-quiz/data.ts', import.meta.url), 'utf8').matchAll(/'([A-Z]{2})'\]/g)].map((m) => m[1]));

const users = new Map();
for (const g of topo.objects.countries.geometries) {
  const iso = BY_NAME[g.properties.name] ?? numToIso.get(g.id);
  if (!iso) continue;
  const polys = g.type === 'Polygon' ? [g.arcs] : g.type === 'MultiPolygon' ? g.arcs : [];
  for (const ring of polys.flat()) for (const a of ring) { const k = a < 0 ? ~a : a; (users.get(k) ?? users.set(k, new Set()).get(k)).add(iso); }
}
const natural = new Map();
const link = (a, b) => { (natural.get(a) ?? natural.set(a, new Set()).get(a)).add(b); };
for (const set of users.values()) if (set.size === 2) { const [a, b] = [...set]; link(a, b); link(b, a); }

const key = (a, b) => [a, b].sort().join('-');
const agreed = new Map(), unsure = new Set();
for (const a of bank) {
  const n = natural.get(a) ?? new Set(), g = geonames.get(a) ?? new Set();
  for (const b of new Set([...n, ...g])) {
    if (!bank.has(b)) continue;
    if (n.has(b) && g.has(b) && geonames.get(b)?.has(a)) (agreed.get(a) ?? agreed.set(a, []).get(a)).push(b);
    else unsure.add(key(a, b));
  }
}
// Known gaps in both sources, kept out as wrong options: the ~150 m Kazungula border (BW-ZM), Morocco/Mauritania across the
// disputed Western Sahara, Hans Island (CA-DK, via Greenland since 2022), Gibraltar (ES-GB) and the UK bases on Cyprus.
for (const pair of ['BW-ZM', 'MA-MR', 'CA-DK', 'ES-GB', 'CY-GB']) unsure.add(pair);
const rows = [...agreed].sort(([a], [b]) => a.localeCompare(b)).map(([a, list]) => `  ${a}: '${list.sort().join(' ')}'`);
const ts = `/**
 * Land borders between countries in the Geo Quiz bank. GENERATED by scripts/generate-capital-quiz-borders.mjs.
 * A pair is listed only when Natural Earth (shared polygon edges in world-atlas 50m) and GeoNames (neighbours column)
 * both agree. UNSURE pairs are known to only one source (overseas territories, disputed areas, very short borders):
 * they are never asked and never offered as a wrong option.
 * Sources: Natural Earth (public domain) via world-atlas; GeoNames countryInfo (CC BY 4.0, https://www.geonames.org/).
 */
export const BORDER_ROWS: Readonly<Record<string, string>> = {
${rows.join(',\n')}
};
export const UNSURE_PAIRS: readonly string[] = ${JSON.stringify([...unsure].sort())};
`;
writeFileSync(out, ts);
console.log(`${agreed.size} countries with neighbours, ${[...agreed.values()].reduce((s, l) => s + l.length, 0) / 2} pairs, unsure: ${[...unsure].sort().join(' ')}`);
