export type Key = keyof typeof STRINGS;

export type I18n = { lang: Lang; t(key: Key, vars?: Record<string, string | number>): string; tr(loc: Loc): string };
export function createI18n(lang: Lang): I18n {
  return {
    lang,
    t(key, vars) {
      const pair = STRINGS[key];
      let text: string = pair ? pair[lang === 'zh' ? 1 : 0] : key;
      if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
      return text;
    },
    tr(loc) { return loc[lang] ?? loc.en; }
  };
}
export const denyKey = (reason: DenyReason): Key => `deny.${reason}` as Key;
