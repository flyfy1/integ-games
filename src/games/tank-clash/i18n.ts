export function t(lang: Lang, key: Key, params?: Record<string, string | number>): string {
  const raw = (lang === 'zh' ? ZH[key] : EN[key]) ?? EN[key];
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? ''));
}
